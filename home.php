                    <h3>What is Graph Paper?</h3>
                    <p>Graph paper is paper meant to be written and drawn on. It is made up of fine lines arranged vertically and horizontally as to create many small boxes.</p>
                    
                    <h3>What is Graph Paper used for?</h3>
                    <p>Graph paper is useful when you want to draw things to some kind of scale, instead of measuring each line with a ruler as you draw it you let the graph paper serve as a guide. Graph paper is available in many different measurements, for example each box can be centimeter or an inch in length.</p>
                    <p>For example anything using the cartesian system can make use of graph paper since the cartesian system is essentially a grid. This makes graph paper ideal for taking notes on math related subjects. For example to plot and study lines, functions, and data.</p>
                    
                    <h3>Other uses of graph paper:</h3>
                    <p>You can use graph paper as a two dimensional ruler. Instead of placing the ruler on the object you can place the object on the paper.</p>
                    <p>You can also use it to do multi digit math. Having multiple numbers in a small space can make it confusing to determine which numbers should be added, subtracted, multiplied, etc. Graph papers keep those numbers neat and aligned.</p>
                    <p>It can also be used as a writing aid, specially for children learning to write.</p>
                    <p>You can fill in blocks in black or color to create graph art.</p>
